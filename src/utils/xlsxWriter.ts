import zlib from "zlib";

/**
 * Minimal, dependency-free .xlsx (Office Open XML) writer. It supports exactly
 * what the monthly report needs: several sheets, a bold frozen header row,
 * text / number / date cells, column widths and an optional bold totals row.
 */

export type XlsxColumnType = "text" | "number" | "date";

export interface XlsxColumn {
  header: string;
  width?: number;
  type?: XlsxColumnType;
}

/** A cell is plain text, a number, or null/undefined for an empty cell. Dates are Excel serial numbers. */
export type XlsxCell = string | number | null | undefined;

export interface XlsxSheet {
  name: string;
  columns: XlsxColumn[];
  rows: XlsxCell[][];
  /** Optional last row rendered in bold (e.g. grand totals). */
  totalsRow?: XlsxCell[];
}

/** Excel serial number (days since 1899-12-30) for a calendar day. */
export function excelDateSerial(
  year: number,
  month1to12: number,
  day: number,
): number {
  return Math.round(Date.UTC(year, month1to12 - 1, day) / 86_400_000) + 25569;
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++)
    c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function xmlEscape(value: string): string {
  return value
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function colName(index: number): string {
  let n = index + 1;
  let s = "";
  while (n > 0) {
    const r = (n - 1) % 26;
    s = String.fromCharCode(65 + r) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

// Cell style ids (see STYLES_XML cellXfs order).
const S_DEFAULT = 0;
const S_HEADER = 1;
const S_NUMBER = 2;
const S_DATE = 3;
const S_TOTAL_TEXT = 4;
const S_TOTAL_NUMBER = 5;

